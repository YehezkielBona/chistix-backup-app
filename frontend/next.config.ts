import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  reactCompiler: true,
  images: {
    remotePatterns: [
      {
        protocol: "https",
        hostname: "images.unsplash.com",
      },
      {
        protocol: "https",
        hostname: "res.cloudinary.com",
      },
    ],
  },

  // Teruskan (proxy) semua request /api/* dari browser ke server Backend Express.
  // Dengan cara ini browser tetap berkomunikasi di origin yang sama (:3000),
  // sehingga bebas masalah CORS dan cookie sesi login tetap tersimpan otomatis.
  async rewrites() {
    const backendUrl = process.env.BACKEND_URL || "http://localhost:4000";
    return [
      {
        source: "/api/:path*",
        destination: `${backendUrl}/api/:path*`,
      },
    ];
  },
};

export default nextConfig;
